#!/usr/bin/env python3
"""
filter_target_freq.py
Step 2 — modern × Gallica corpus:
  Apply the excluded filename list generated by filter_source_freq.py,
  this time checking target_filename (Gallica texts appear as targets here).

Usage:
    python3 filter_target_freq.py
"""

import json

INPUT    = "/path/to/alignements/modern_gallica/output/alignments_clean3.jsonl"
OUTPUT   = "/path/to/alignements/modern_gallica/output/alignments_clean4.jsonl"
EXCL_IN  = "/path/to/alignements/excluded_filenames.json"

with open(EXCL_IN) as f:
    excluded = set(json.load(f))
print(f"Loaded {len(excluded):,} excluded filenames.", flush=True)

kept = removed = 0
with open(INPUT, "rb") as fh, open(OUTPUT, "wb") as fout:
    for n, line in enumerate(fh, 1):
        line = line.strip()
        if not line:
            continue
        try:
            rec = json.loads(line)
        except Exception:
            continue
        if rec.get("target_filename", "") in excluded:
            removed += 1
        else:
            fout.write(line + b"\n")
            kept += 1
        if n % 100_000 == 0:
            print(f"  {n:,} processed | kept {kept:,} removed {removed:,}", flush=True)

print(f"\nDone.")
print(f"  Input:   {kept + removed:,} records")
print(f"  Kept:    {kept:,}")
print(f"  Removed: {removed:,}  (target_filename in excluded list)")
print(f"  Output:  {OUTPUT}")
